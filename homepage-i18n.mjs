export function matchLanguage(value) {
  if (typeof value !== 'string') return null;
  const language = value.toLowerCase();
  if (/^zh-hans(?:-|$)/.test(language) || /^zh-(?:cn|sg)(?:-|$)/.test(language)) return 'zh-Hans';
  if (language === 'zh' || /^zh-(?:hant|tw|hk|mo)(?:-|$)/.test(language)) return 'zh-Hant';
  if (/^en(?:-|$)/.test(language)) return 'en';
  if (/^ja(?:-|$)/.test(language)) return 'ja';
  return null;
}

export function chooseLanguage(saved, browserLanguages = []) {
  if (LANGUAGES.includes(saved)) return saved;
  for (const language of browserLanguages) {
    const match = matchLanguage(language);
    if (match) return match;
  }
  return 'zh-Hant';
}

export function projectCountText(language, count) {
  const messages = TEXT[language] || TEXT['zh-Hant'];
  return messages[count === 1 ? 'countOne' : 'countOther'].replace('{count}', new Intl.NumberFormat(language).format(count));
}
